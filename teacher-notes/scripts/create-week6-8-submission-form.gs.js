/**
 * 第六週・掃描行動 任務繳交（八年級） —— Google Apps Script，自動建立Google表單
 * 收「姓名＋.sb3專案檔案＋掃描結果截圖」，不是選擇題測驗——積木邏輯對不對由老師打開
 * 學生交的.sb3檔案自己看，截圖只是輔助老師快速比對「跑完之後說出的最大值對不對」，
 * 不是表單自動評分，所以不用設測驗模式。
 *
 * **重要限制（Apps Script做不到的部分）**：Google的FormApp服務沒有開放「用程式建立
 * 檔案上傳題」這個功能（`addFileUploadItem`這個建立用的方法根本不存在，這是Google
 * 故意沒開放的，不是語法錯誤）——檔案上傳題只能透過表單編輯畫面手動加。所以這份Script
 * 只負責建立表單本體、說明文字、跟「班級座號姓名」這一題，另外兩題檔案上傳要跑完
 * Script後自己手動加，步驟見下面第5點。
 *
 * 使用方式：
 * 1. 開啟 https://script.google.com/ → 新增專案
 * 2. 把這個檔案的內容整個貼到編輯器裡（取代預設的 myFunction）
 * 3. 上方選單選 createForm 這個函式，按執行（第一次會要求授權，允許即可）
 * 4. 執行完成後，左下角「執行紀錄」會印出：
 *    - 編輯用網址（自己修改題目用，接下來手動加題要用這個網址開）
 *    - 填答/嵌入用網址（要貼回 week6-8-intro.md frontmatter 的 embeds.url，取代
 *      PLACEHOLDER_FORM_ID）
 * 5. **手動加兩題檔案上傳**：打開編輯用網址，在「Scratch專案繳交」這個分頁區段裡，
 *    用左邊「＋」新增問題，問題類型選「檔案上傳」，依序加這兩題：
 *    - 標題：請上傳你的Scratch專案檔案（.sb3）
 *      說明文字：先在Scratch點選單「檔案→匯出到你的電腦」下載.sb3檔案，依格式重新
 *                命名後再上傳。這一題沒辦法限定副檔名，麻煩自己上傳前再檢查一次
 *                副檔名真的是.sb3。
 *      設定：允許的檔案類型選「所有檔案類型」（Google表單的檔案類型清單沒有.sb3
 *            這種壓縮檔/自訂副檔名的選項，只能選最寬鬆的這個）、上限1個檔案、
 *            必填打開
 *    - 標題：請上傳按下 s 鍵掃描之後，程式說出最大值的畫面截圖
 *      說明文字：按下 s 鍵執行掃描，畫面上應該會說出「最大值是：990」，截圖上傳
 *                這個畫面。
 *      設定：允許的檔案類型選「圖片」、上限1個檔案、必填打開
 * 6. 建議把表單的「回覆」分頁連結到一張Google試算表（表單編輯畫面右上角「回覆」分頁
 *    → 綠色試算表圖示），方便照著名單一個一個點開附件檢查、手動評分。
 * 7. 「班級座號姓名」用正規表示法擋格式（例如 801_05_王小明），格式不對無法送出。
 *    這份表單不是測驗模式，這格不計分、也不會自動評分，Scratch積木邏輯還是要
 *    老師自己下載.sb3檔案打開來看。
 * 8. **重要**：表單裡只要有檔案上傳題，Google表單會自動要求填答者先登入Google帳號
 *    才能填寫（這是Google的平台限制），學生用學校Gmail登入後就能正常上傳，不用
 *    另外處理。上傳的檔案會存進一個自動建立、跟這份表單綁在一起的雲端硬碟資料夾，
 *    在表單編輯畫面的「回覆」分頁可以連到那個資料夾。
 *
 * 表單分成兩個區段：區段一只有「班級座號姓名」，區段二是手動加的「Scratch專案檔案＋
 * 掃描結果截圖」兩題檔案上傳。這份表單維持非測驗模式，但下面這幾項一般表單設定
 * createForm() 已經自動設定：收集電子郵件、限制每人只能回覆1次、問題順序隨機。
 * 以下2項 Google Forms 目前沒有開放 Apps Script 用程式設定，執行完 createForm()
 * 之後，麻煩自己到表單右上角⚙️（設定）→「回覆」分頁手動確認/勾選一次：
 * 1.「收集電子郵件地址」確認是選「已驗證」，不是「回覆者輸入」。
 * 2.「傳送回覆者回覆副本」選「一律」。
 * （這份表單沒有單選題，不需要處理選項洗牌；問題順序隨機也建議手動加完檔案上傳題後
 * 再檢查一次，確認「班級座號姓名」還是排在最前面比較好核對。）
 */
function createForm() {
  var form = FormApp.create('W6-8-掃描行動・任務繳交');
  form.setDescription(
    '完成「排行榜分數」清單跟按s鍵掃描找最大值的積木之後，先點Scratch選單「檔案→匯出到' +
      '你的電腦」，把.sb3檔案下載下來，再依格式重新命名，回來這份表單上傳。'
  );
  form.setCollectEmail(true);
  form.setLimitOneResponsePerUser(true);
  form.setShuffleQuestions(true);

  addNameIdItem(form);

  form.addPageBreakItem().setTitle('Scratch專案繳交');

  // Apps Script沒辦法用程式建立檔案上傳題（FormApp沒有addFileUploadItem這個建立用的
  // 方法），這兩題「.sb3專案檔案」「掃描結果截圖」要手動加，設定值見檔案最上面的
  // 使用說明第5點。

  Logger.log('編輯用網址（自己改題目用）：' + form.getEditUrl());
  Logger.log('接下來請手動到編輯畫面加兩題檔案上傳，設定值見本檔案最上面的使用說明第5點');
  // 一定要加 ?embedded=true，不然嵌入iframe會被Google擋掉（顯示「docs.google.com拒絕連線」）
  Logger.log('填答/嵌入用網址（可直接貼到 week6-8-intro.md 的 embeds.url）：' + form.getPublishedUrl() + '?embedded=true');
}

/** 「班級座號姓名」格式：班級(17開頭)+班級編號(01~10)_座號(01~27)_姓名(2~4個中文字)。 */
var NAME_ID_PATTERN = '^[1278](0[1-9]|10)_(0[1-9]|1[0-9]|2[0-7])_[一-龥]{2,4}$';

/** 新增「班級座號姓名」文字題，用正規表示法擋格式（這份表單非測驗模式，不計分）。 */
function addNameIdItem(form) {
  var item = form.addTextItem();
  item
    .setTitle('請輸入 班級座號姓名（格式：班級_座號_姓名，例如 710_16_王小明）')
    .setHelpText('格式：班級_座號_姓名，例如 710_16_王小明。')
    .setRequired(true)
    .setValidation(
      FormApp.createTextValidation()
        .setHelpText('格式錯誤，請依照 班級_座號_姓名 輸入，例如 710_16_王小明。')
        .requireTextMatchesPattern(NAME_ID_PATTERN)
        .build()
    );
  return item;
}
